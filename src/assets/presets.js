export function presetRows(id, owner) {
  const p = PRESETS.find(x => x.id === id)
  if (!p) return []
  const items = p.cards.map(([type, x, y, o], i) => ({ ...makeItem(type, { x, y: y + 90, owner, layer: 'main', z: Date.now() + i, ...o }), id: uid(), pin: { x: .5, y: .05 } }))
  return [
    ...items.map(d => ({ kind: 'item', data: d })),
    ...items.map(it => ({ kind: 'history', data: { id: uid(), item: it.id, author: owner, action: 'create', ts: Date.now(), snap: { title: it.title, text: it.text } } })),
  ]
}
